"""
Action tools for MCP Server.
Allows the ShadowLens autonomous agent to take remediation actions, create findings,
and modify security controls based on graph evidence.
Supports safe simulation mode with cryptographic verification receipts.
"""

from __future__ import annotations

import datetime
import hashlib
import logging
import uuid
from typing import TYPE_CHECKING, Any, Dict, List, Optional
from pydantic import BaseModel, Field

from src.graph.graph_store import get_graph_store
from src.graph.schema import EntityType, GraphEdge, GraphNode, RelationType

if TYPE_CHECKING:
    from src.mcp.server import MCPServer

logger = logging.getLogger(__name__)


class FindingRecord(BaseModel):
    finding_id: str
    title: str
    severity: str  # CRITICAL, HIGH, MEDIUM, LOW
    affected_entities: List[str]
    description: str
    evidence_paths: List[List[str]] = Field(default_factory=list)
    status: str = "OPEN"  # OPEN, TRIAGED, MITIGATED, RESOLVED
    created_at: str
    updated_at: str
    notes: List[str] = Field(default_factory=list)


class ActionReceipt(BaseModel):
    action_id: str
    action_type: str
    target_entity_id: str
    status: str  # "PROPOSED", "AWAITING_APPROVAL", "APPROVED", "REJECTED", "EXECUTED", "FAILED"
    simulation_mode: bool
    summary: str
    details: Dict[str, Any]
    blast_radius_preview: Dict[str, Any] = Field(default_factory=dict)
    timestamp: str
    verification_hash: str
    approved_by: Optional[str] = None
    approved_at: Optional[str] = None
    rejection_reason: Optional[str] = None


# Global In-Memory Registries (can also be synced with MongoDB)
FINDINGS_REGISTRY: Dict[str, FindingRecord] = {}
ACTIONS_REGISTRY: Dict[str, ActionReceipt] = {}


def create_finding(
    title: str,
    severity: str,
    affected_entities: List[str],
    description: str,
    evidence_paths: Optional[List[List[str]]] = None,
) -> Dict[str, Any]:
    """
    Create a formal security finding backed by graph evidence.
    Also links the new Finding node into the live knowledge graph!
    """
    finding_id = f"FND-{uuid.uuid4().hex[:8].upper()}"
    now_iso = datetime.datetime.utcnow().isoformat() + "Z"

    record = FindingRecord(
        finding_id=finding_id,
        title=title,
        severity=severity.upper(),
        affected_entities=affected_entities,
        description=description,
        evidence_paths=evidence_paths or [],
        status="OPEN",
        created_at=now_iso,
        updated_at=now_iso,
        notes=["Auto-generated by ShadowLens Autonomous Investigation Agent"],
    )
    FINDINGS_REGISTRY[finding_id] = record

    # Dynamically inject Finding node into the live graph
    store = get_graph_store()
    store.add_node(
        GraphNode(
            id=finding_id,
            label=f"Finding: {title}",
            type=EntityType.FINDING,
            risk_level=severity.upper(),
            risk_score=0.9 if severity.upper() in ("CRITICAL", "HIGH") else 0.5,
            properties={"finding_id": finding_id, "status": "OPEN", "description": description},
        )
    )

    # Add edges from finding to affected entities
    for target_id in affected_entities:
        if store.get_node(target_id):
            store.add_edge(
                GraphEdge(
                    source=finding_id,
                    target=target_id,
                    type=RelationType.AFFECTS,
                    properties={"auto_linked": True},
                )
            )

    logger.info(f"Created finding {finding_id}: {title} [{severity}]")
    return {
        "created": True,
        "finding_id": finding_id,
        "title": title,
        "severity": severity,
        "affected_entities": affected_entities,
        "message": f"Security finding {finding_id} successfully recorded and linked into knowledge graph.",
    }


def update_finding(finding_id: str, status: str, note: Optional[str] = None) -> Dict[str, Any]:
    """Update status (e.g. TRIAGED, MITIGATED, RESOLVED) or append investigation notes."""
    if finding_id not in FINDINGS_REGISTRY:
        return {"updated": False, "finding_id": finding_id, "error": "Finding not found"}

    f = FINDINGS_REGISTRY[finding_id]
    f.status = status.upper()
    f.updated_at = datetime.datetime.utcnow().isoformat() + "Z"
    if note:
        f.notes.append(note)

    # Update node in graph
    store = get_graph_store()
    node = store.get_node(finding_id)
    if node:
        node.properties["status"] = status.upper()

    return {
        "updated": True,
        "finding_id": finding_id,
        "new_status": f.status,
        "notes_count": len(f.notes),
    }


def take_remediation_action(
    action_type: str,
    target_entity_id: str,
    parameters: Optional[Dict[str, Any]] = None,
    simulation: bool = True,
    require_approval: bool = True,
) -> Dict[str, Any]:
    """
    Proposes or executes autonomous remediation on the target entity based on discovered graph evidence.
    Consequential actions default to requiring human approval (require_approval=True),
    computing a pre-execution graph blast radius preview.
    """
    action_id = f"ACT-{uuid.uuid4().hex[:8].upper()}"
    now_iso = datetime.datetime.utcnow().isoformat() + "Z"
    params = parameters or {}

    # 1. Compute Graph Blast Radius Preview
    store = get_graph_store()
    blast_radius = store.get_blast_radius(target_entity_id, max_depth=4)

    # Verification cryptographic proof
    proof_material = f"{action_id}:{action_type}:{target_entity_id}:{now_iso}:{simulation}"
    v_hash = hashlib.sha256(proof_material.encode("utf-8")).hexdigest()[:16]

    action_summaries = {
        "quarantine_endpoint": f"Enforce ingress traffic isolation and rate-limiting on endpoint '{target_entity_id}'.",
        "revoke_iam_permission": f"Revoke wildcard privileges on IAM role '{target_entity_id}' and enforce Least Privilege.",
        "patch_dependency": f"Dispatch automated dependency bump and security pin for '{target_entity_id}'.",
        "block_input_source": f"Blacklist malicious input vectors reaching '{target_entity_id}'.",
        "isolate_database_table": f"Enforce query param validation and connection isolation for '{target_entity_id}'.",
    }

    summary = action_summaries.get(
        action_type,
        f"Remediation '{action_type}' on target '{target_entity_id}'.",
    )

    initial_status = "AWAITING_APPROVAL" if require_approval else ("SIMULATED_SUCCESS" if simulation else "EXECUTED_SUCCESS")

    receipt = ActionReceipt(
        action_id=action_id,
        action_type=action_type,
        target_entity_id=target_entity_id,
        status=initial_status,
        simulation_mode=simulation,
        summary=summary,
        details={
            "parameters": params,
            "target": target_entity_id,
            "rollback_plan": f"Restore original state via ID {action_id}-ROLLBACK",
            "enforcement_agent": "ShadowLens Autonomous Response Agent",
        },
        blast_radius_preview=blast_radius,
        timestamp=now_iso,
        verification_hash=v_hash,
    )
    ACTIONS_REGISTRY[action_id] = receipt

    # Update node risk level in graph store
    node = store.get_node(target_entity_id)
    if node:
        node.properties["remediation_action_id"] = action_id
        node.properties["remediation_status"] = "AWAITING_APPROVAL" if require_approval else ("MITIGATED (SIMULATION)" if simulation else "MITIGATED")

    logger.info(f"Remediation action {action_id} [{action_type}] on {target_entity_id} - Status: {initial_status} - Blast Radius: {blast_radius.get('blast_count')} nodes")
    return {
        "success": True,
        "action_id": action_id,
        "action_type": action_type,
        "target_entity_id": target_entity_id,
        "simulation": simulation,
        "status": receipt.status,
        "summary": summary,
        "blast_radius_preview": blast_radius,
        "verification_hash": v_hash,
        "receipt": receipt.model_dump(),
    }


def approve_action(action_id: str, approver: str = "security_lead") -> Dict[str, Any]:
    """Approves and executes a proposed action requiring human approval."""
    if action_id not in ACTIONS_REGISTRY:
        return {"success": False, "error": f"Action ID '{action_id}' not found"}

    receipt = ACTIONS_REGISTRY[action_id]
    if receipt.status != "AWAITING_APPROVAL":
        return {"success": False, "error": f"Action is already in status '{receipt.status}'"}

    now_iso = datetime.datetime.utcnow().isoformat() + "Z"
    receipt.status = "EXECUTED_SIMULATION" if receipt.simulation_mode else "EXECUTED"
    receipt.approved_by = approver
    receipt.approved_at = now_iso

    # Update node in graph
    store = get_graph_store()
    node = store.get_node(receipt.target_entity_id)
    if node:
        node.properties["remediation_status"] = "APPROVED & ENFORCED (SIMULATION)" if receipt.simulation_mode else "APPROVED & ENFORCED"
        node.risk_level = "LOW"

    logger.info(f"Action {action_id} APPROVED by {approver}. New status: {receipt.status}")
    return {
        "success": True,
        "action_id": action_id,
        "status": receipt.status,
        "approved_by": approver,
        "approved_at": now_iso,
        "receipt": receipt.model_dump(),
    }


def reject_action(action_id: str, reason: str = "Rejected by operator") -> Dict[str, Any]:
    """Rejects a proposed action."""
    if action_id not in ACTIONS_REGISTRY:
        return {"success": False, "error": f"Action ID '{action_id}' not found"}

    receipt = ACTIONS_REGISTRY[action_id]
    receipt.status = "REJECTED"
    receipt.rejection_reason = reason

    # Update node in graph
    store = get_graph_store()
    node = store.get_node(receipt.target_entity_id)
    if node:
        node.properties["remediation_status"] = f"REJECTED: {reason}"

    logger.info(f"Action {action_id} REJECTED. Reason: {reason}")
    return {
        "success": True,
        "action_id": action_id,
        "status": "REJECTED",
        "rejection_reason": reason,
        "receipt": receipt.model_dump(),
    }


def register_action_tools(server: MCPServer) -> None:
    server.register_tool(
        name="create_finding",
        description="Create a formal security finding with severity, affected entities, and discovered attack path evidence. Injects finding into the knowledge graph.",
        parameters={
            "type": "object",
            "properties": {
                "title": {"type": "string", "description": "Concise finding title (e.g. 'Unsanitized Multi-Hop SQL Injection Vector')"},
                "severity": {"type": "string", "enum": ["CRITICAL", "HIGH", "MEDIUM", "LOW"], "description": "Risk severity"},
                "affected_entities": {
                    "type": "array",
                    "items": {"type": "string"},
                    "description": "List of node IDs directly affected by or involved in this finding",
                },
                "description": {"type": "string", "description": "Technical description of the vulnerability and attack vector"},
                "evidence_paths": {
                    "type": "array",
                    "items": {"type": "array", "items": {"type": "string"}},
                    "description": "Optional list of node ID chains forming the attack path",
                },
            },
            "required": ["title", "severity", "affected_entities", "description"],
        },
        handler=create_finding,
        category="action",
    )

    server.register_tool(
        name="update_finding",
        description="Update an existing finding's status or append triage notes",
        parameters={
            "type": "object",
            "properties": {
                "finding_id": {"type": "string", "description": "Finding ID (e.g. 'FND-A1B2C3D4' or 'finding:sec-309-priv-esc')"},
                "status": {"type": "string", "enum": ["OPEN", "TRIAGED", "MITIGATED", "RESOLVED"], "description": "New status"},
                "note": {"type": "string", "description": "Optional note to append to the finding's audit log"},
            },
            "required": ["finding_id", "status"],
        },
        handler=update_finding,
        category="action",
    )

    server.register_tool(
        name="take_remediation_action",
        description="Execute an autonomous mitigation or defensive action on a target node (e.g., quarantine_endpoint, revoke_iam_permission, patch_dependency, block_input_source, isolate_database_table). Runs in safe simulation mode by default.",
        parameters={
            "type": "object",
            "properties": {
                "action_type": {
                    "type": "string",
                    "enum": [
                        "quarantine_endpoint",
                        "revoke_iam_permission",
                        "patch_dependency",
                        "block_input_source",
                        "isolate_database_table",
                    ],
                    "description": "Type of remediation action to execute",
                },
                "target_entity_id": {"type": "string", "description": "Entity ID on which to perform remediation"},
                "parameters": {"type": "object", "description": "Optional action parameters (e.g. isolation duration, rule set)"},
                "simulation": {"type": "boolean", "default": True, "description": "Whether to run in safe simulation mode"},
            },
            "required": ["action_type", "target_entity_id"],
        },
        handler=take_remediation_action,
        category="action",
    )
